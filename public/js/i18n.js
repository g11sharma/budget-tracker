'use strict';
/*
 * English / French.
 * The English text is the key: tr('Saved') shows "Saved" in English and FR['Saved'] in French.
 * A text missing from FR simply shows in English. {name} placeholders are filled from `vars`;
 * values are inserted as given, so escape user text with esc() before passing it into HTML.
 */
const LANG_KEY = 'moneyLeakTracker.lang';
let LANG = (() => {
  let l = null; try { l = localStorage.getItem(LANG_KEY); } catch (e) {}
  return l === 'fr' || l === 'en' ? l : (/^fr\b/i.test(navigator.language || '') ? 'fr' : 'en');
})();
const LOCALE = () => LANG === 'fr' ? 'fr-FR' : 'en-GB';
function tr(s, vars){
  let out = LANG === 'fr' && Object.prototype.hasOwnProperty.call(FR, s) ? FR[s] : s;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => vars[k] != null ? String(vars[k]) : m);
  return out;
}
// one/many by English rules; vars may override {n} (e.g. to make the number bold)
function trn(n, one, many, vars){ return tr(n === 1 ? one : many, {n, ...vars}); }
// Texts written in index.html: data-i18n (text), data-i18n-ph (placeholder), data-i18n-aria (aria-label)
function applyStaticI18n(){
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = tr(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', tr(el.dataset.i18nAria)); });
  const b = document.getElementById('langBtn');
  if (b){ b.textContent = LANG === 'fr' ? 'EN' : 'FR'; b.title = LANG === 'fr' ? 'Switch to English' : 'Passer en français'; b.setAttribute('aria-label', b.title); b.lang = LANG === 'fr' ? 'en' : 'fr'; }
}

